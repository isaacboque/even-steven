import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { runAll, toMarkdown } from "../src/eval/run.js";

const results = await runAll();
const md = toMarkdown(results);
mkdirSync("eval", { recursive: true });
writeFileSync("eval/RESULTS.md", `# Evaluation results\n\nGenerated by \`npm run eval\` (20 deterministic scenarios, simulated clock, MockGateway).\n\n${md}`);
const readme = readFileSync("README.md", "utf8");
const block = `<!-- eval:start -->\n${md}<!-- eval:end -->`;
writeFileSync("README.md", readme.includes("<!-- eval:start -->") ? readme.replace(/<!-- eval:start -->[\s\S]*<!-- eval:end -->/, block) : `${readme}\n## Evaluation\n\n${block}\n`);
console.log(md);
const failed = results.filter((r) => Object.values(r.checks).some((v) => !v));
if (failed.length) {
  console.error(`${failed.length} scenario(s) failed`);
  process.exit(1);
}
